const header = ['hotel', 'id', 'user_message', 'expected_intent', 'expected_response', 'tool_required', 'notes'];

function csvEscape(value) {
  const s = String(value ?? '');
  if (/[",\n]/.test(s)) {
    return '"' + s.replace(/"/g, '""') + '"';
  }
  return s;
}

function toCsvRow(fields) {
  return fields.map(csvEscape).join(',');
}

const guestQuestionsLines = [toCsvRow(header)];
const intentsLines = [toCsvRow(['hotel', 'id', 'user_message', 'expected_intent'])];

rows.forEach((row, index) => {
  const id = `gq_${String(index + 1).padStart(3, '0')}`;
  const [userMessage, intent, toolRequired, expectedResponse, notes] = row;
  guestQuestionsLines.push(toCsvRow([HOTEL_ID, id, userMessage, intent, expectedResponse, toolRequired ? 'true' : 'false', notes]));
  intentsLines.push(toCsvRow([HOTEL_ID, id, userMessage, intent]));
});

const outDir = __dirname;
fs.writeFileSync(path.join(outDir, 'guest_questions.csv'), guestQuestionsLines.join('\n') + '\n');
fs.writeFileSync(path.join(outDir, 'intents.csv'), intentsLines.join('\n') + '\n');

console.log(`Wrote ${rows.length} rows to guest_questions.csv and intents.csv`);
